// api/generate-exam.js — CommonJS

/** @typedef {'B1'|'B2'|'C1'|'C2'} ExamLevel */
/** @typedef {'Reading'|'Use of English'|'Listening'|'Writing'|'Speaking'} ExamSection */

function nowId(prefix = 'exam') {
  const t = Date.now();
  return `${prefix}-${t}-${Math.random().toString(36).slice(2, 8)}`;
}
function coerceSection(s) {
  const m = String(s || '').trim().toLowerCase();
  if (m.includes('use')) return 'Use of English';
  if (m.startsWith('read')) return 'Reading';
  if (m.startsWith('listen')) return 'Listening';
  if (m.startsWith('writ')) return 'Writing';
  if (m.startsWith('speak')) return 'Speaking';
  return 'Reading';
}
function fallbackExam(level, sections) {
  const ts = Date.now();
  const secs = (Array.isArray(sections) && sections.length)
    ? sections
    : ['Reading', 'Use of English', 'Listening'];
  return {
    id: nowId('fallback'),
    title: `Simulacro ${level}`,
    level,
    sections: secs,
    createdAt: ts,
    items: [
      {
        id: `mcq-${ts}`,
        type: 'mcq',
        prompt: `[${level}] Choose the correct option to complete the sentence.`,
        options: ['A','B','C','D'],
        answer: 1,
        section: 'Reading',
        points: 1,
      },
      {
        id: `gap-${ts}`,
        type: 'gap',
        prompt: `[${level}] Fill the gap with the correct form of the word in brackets.`,
        answer: 'example',
        section: 'Use of English',
        points: 1,
      },
    ],
  };
}

// ------- Proveedor: OLLAMA local -------
async function callOllama(payload) {
  const base = (process.env.EXAM_AI_BASE_URL || 'http://localhost:11434').replace(/\/+$/, '');
  const model = process.env.EXAM_AI_MODEL || 'qwen2.5:7b-instruct';

  const schema = {
    type: 'object',
    required: ['id','title','level','sections','items','createdAt'],
    properties: {
      id: { type: 'string' },
      title: { type: 'string' },
      level: { enum: ['B1','B2','C1','C2'] },
      sections: { type: 'array', items: { enum: ['Reading','Use of English','Listening','Writing','Speaking'] } },
      items: {
        type: 'array',
        items: {
          type: 'object',
          required: ['id','type','prompt','section'],
          properties: {
            id: { type: 'string' },
            type: { enum: ['mcq','gap','open'] },
            prompt: { type: 'string' },
            options: { type: 'array', items: { type: 'string' } },
            answer: {},
            section: { enum: ['Reading','Use of English','Listening','Writing','Speaking'] },
            points: { type: 'number' }
          }
        }
      },
      createdAt: { type: 'number' }
    }
  };

  const system = 'You are an expert Cambridge English exam generator. Return ONLY one JSON object strictly matching the provided JSON schema in format. No markdown.';
  const user = {
    level: payload.level,
    sections: payload.sections,
    itemsPerSection: 2,
    rules: [
      "For MCQ include 4 options and put the correct index in 'answer' (0-based)",
      "For GAP provide a sentence with one blank and a single-word answer",
      "For OPEN give a concise writing/speaking-style prompt",
      "Keep prompts in English",
      "Use exact section labels"
    ]
  };

  const res = await fetch(`${base}/api/chat`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      model,
      stream: false,
      format: schema,
      messages: [
        { role: 'system', content: system },
        { role: 'user', content: JSON.stringify(user) }
      ]
    })
  });

  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`Ollama ${res.status}: ${text.slice(0, 200)}`);
  }

  const data = await res.json();
  const content = data?.message?.content;
  if (!content || typeof content !== 'string') throw new Error('Empty content from Ollama');

  const parsed = JSON.parse(content);
  const lvl = parsed.level || payload.level;
  const secs = Array.isArray(parsed.sections) ? parsed.sections.map(coerceSection) : payload.sections.map(coerceSection);
  const itemsRaw = Array.isArray(parsed.items) ? parsed.items : [];

  const items = itemsRaw.slice(0, 10).map((it, idx) => ({
    id: String(it?.id ?? `it-${idx}-${Date.now()}`),
    type: (it?.type === 'mcq' || it?.type === 'gap' || it?.type === 'open') ? it.type : 'open',
    prompt: String(it?.prompt ?? 'Write a short answer.'),
    options: Array.isArray(it?.options) ? it.options.map(String).slice(0, 6) : undefined,
    answer: it?.answer,
    section: coerceSection(it?.section || secs[0] || 'Reading'),
    points: (typeof it?.points === 'number') ? it.points : 1,
  }));

  if (!items.length) throw new Error('No items generated by Ollama');

  return {
    id: String(parsed.id ?? nowId('ollama')),
    title: String(parsed.title ?? `Mock ${lvl}`),
    level: lvl,
    sections: secs,
    items,
    createdAt: (typeof parsed.createdAt === 'number') ? parsed.createdAt : Date.now(),
  };
}

// ------- (Opcional) proveedor OpenAI-compatible (no usado si EXAM_AI_PROVIDER=ollama) -------
async function callOpenAICompat(payload) {
  const base = process.env.EXAM_AI_BASE_URL;
  const key = process.env.EXAM_AI_API_KEY;
  const model = process.env.EXAM_AI_MODEL;
  if (!base || !key || !model) throw new Error('Missing EXAM_AI_* environment variables');

  const system = 'You are an expert Cambridge English exam generator. Return ONLY a single JSON object; no markdown.';
  const user = { level: payload.level, sections: payload.sections, itemsPerSection: 2 };

  const res = await fetch(`${base.replace(/\/+$/, '')}/chat/completions`, {
    method: 'POST',
    headers: { 'content-type': 'application/json', authorization: `Bearer ${key}` },
    body: JSON.stringify({
      model,
      stream: false,
      response_format: { type: 'json_object' },
      messages: [
        { role: 'system', content: system },
        { role: 'user', content: JSON.stringify(user) },
      ],
    }),
  });

  if (!res.ok) {
    const text = await res.text().catch(() => '');
    throw new Error(`Provider ${res.status}: ${text.slice(0, 200)}`);
  }
  const json = await res.json();
  const content = json?.choices?.[0]?.message?.content;
  const parsed = JSON.parse(content);
  return parsed;
}

module.exports = async (req, res) => {
  try {
    if (req.method !== 'POST') {
      res.setHeader('Allow', 'POST');
      return res.status(405).json({ error: 'Method Not Allowed' });
    }

    const body = (typeof req.body === 'string' ? JSON.parse(req.body) : req.body) || {};
    const valid = new Set(['B1','B2','C1','C2']);
    const lvl = valid.has(body.level) ? body.level : 'B2';
    const secs = Array.isArray(body.sections) && body.sections.length
      ? body.sections.map(coerceSection)
      : ['Reading', 'Use of English', 'Listening'];

    const provider = String(process.env.EXAM_AI_PROVIDER || 'openai_compat').toLowerCase();
    let exam;
    try {
      exam = provider === 'ollama'
        ? await callOllama({ level: lvl, sections: secs })
        : await callOpenAICompat({ level: lvl, sections: secs });
      return res.status(200).json(exam);
    } catch (e) {
      console.warn('[api/generate-exam] provider failed, fallback:', e?.message || e);
    }

    return res.status(200).json(fallbackExam(lvl, secs));
  } catch (e) {
    console.error('[api/generate-exam] fatal:', e?.stack || e);
    return res.status(500).json({ error: 'internal_error', message: e?.message || 'Unknown error' });
  }
};
